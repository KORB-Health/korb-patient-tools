#!/usr/bin/env node
/* ============================================================================
   KORB HEALTH — OPTIMIZATION PRODUCTS SIGN-OFF SHEET

   Generates the sheet the Director of Clinical Operations reads before the
   23 formulations in korb-addons-data.js go live in the provider tool.

   Generated from the data file rather than hand-written, for the same reason
   the monograph sheet is: a sheet transcribed by hand can describe text the
   reviewer is not actually approving.

   Two groups, and the difference matters:
     COMPLETE   — every Tebra field is filled. Sign off or correct.
     INCOMPLETE — name, formulation and days are confirmed but the sig and
                  quantity are not written yet. These need the fields supplied,
                  not just approved. The tool marks them in the same way.

   USAGE  node build-addon-signoff.js > KORB_Optimization_Products_Signoff.md
   ============================================================================ */

'use strict';

const path = require('path');
const A = require(path.join(__dirname, 'korb-addons-data.js'));

function fieldsMissing(p) {
  const t = p.tebra || {};
  const missing = [];
  if (!t.sig) missing.push('Patient Instructions (sig)');
  if (t.quantity === null || t.quantity === undefined) missing.push('Quantity');
  if (!t.unit) missing.push('Unit');
  if (!t.pharmacyNotes) missing.push('Pharmacy Instructions');
  return missing;
}

const complete = [], incomplete = [];
A.products.forEach(function (p) {
  (fieldsMissing(p).length ? incomplete : complete).push(p);
});

const PHARM = { premier: 'Premier', farmakeio: 'FarmaKeio', belmar: 'Belmar' };
const SEX = { any: 'Any', m: 'Male', f: 'Female' };

const out = [];
const line = s => out.push(s === undefined ? '' : s);

line('# KORB Optimization Products — Formulation Sign-Off');
line();
line('Generated from `korb-addons-data.js` on ' + new Date().toISOString().slice(0, 10) + '.');
line('Do not edit this file. Correct the data file and regenerate.');
line();
line('**' + A.products.length + ' formulations.** ' + complete.length + ' complete, '
     + incomplete.length + ' awaiting fields.');
line();
line('Every record carries `needsSignoff: true`. Nothing here has been through a');
line('clinical review. These were extracted from the Add-On Clinical Reference and the');
line('tool\'s own prior code, so treat each line as a transcription to verify rather');
line('than a claim to accept.');
line();
line('---');
line();
line('## What to check on each');
line();
line('1. **Formulation** — the actual compound and strengths.');
line('2. **Tebra name** — follows `PHARMACY – Product Strength – N-Day Supply`.');
line('3. **Sig** — what the patient is told to do, and whether it fits the 140-character');
line('   Tebra Patient Instructions cap.');
line('4. **Quantity, unit and days** — that they agree with each other and with the');
line('   supply the patient is actually paying for.');
line('5. **Price and charge code** — against the billing sheet, not against this file.');
line();

function table(list, heading, note) {
  line('---');
  line();
  line('## ' + heading);
  line();
  if (note) { line(note); line(); }

  const byCat = {};
  list.forEach(function (p) { (byCat[p.category] = byCat[p.category] || []).push(p); });

  Object.keys(byCat).sort().forEach(function (cat) {
    line('### ' + cat);
    line();
    byCat[cat].forEach(function (p) {
      const t = p.tebra || {};
      const missing = fieldsMissing(p);
      line('#### ' + p.name + '  ·  ' + (PHARM[p.pharmacy] || p.pharmacy));
      line();
      line('| Field | Value |');
      line('| --- | --- |');
      line('| Patient sex | ' + (SEX[p.sex] || p.sex) + ' |');
      line('| Formulation | ' + (p.formulation || '—') + ' |');
      line('| Dosing | ' + (p.dosing || '—') + ' |');
      line('| Supply | ' + (p.supply || '—') + ' |');
      line('| Price | ' + (p.price || '—') + ' |');
      line('| Charge code | `' + (p.chargeCode || '—') + '` |');
      line('| Tebra name | ' + (t.name || '—') + ' |');
      line('| Drug Formulation | ' + (p.drugFormulation || '—') + ' |');
      line('| Sig | ' + (t.sig || '**not written**') + ' |');
      line('| Quantity / unit | ' + (t.quantity == null ? '**not set**' : t.quantity)
           + ' ' + (t.unit || '') + ' |');
      line('| Days | ' + (t.days == null ? '**not set**' : t.days) + ' |');
      line('| Reason for compounding | ' + (t.reasonForCompounding || '—') + ' |');
      line('| Pharmacy Instructions | ' + (t.pharmacyNotes || '**not written**') + ' |');
      line();
      if (t.sig) {
        const n = t.sig.length;
        line('Sig length: **' + n + ' / 140** characters'
             + (n > 140 ? ' — **OVER THE TEBRA CAP, will truncate**' : '') + '.');
        line();
      }
      if (missing.length) {
        line('**Missing:** ' + missing.join(', ') + '.');
        line();
      }
      if (p.warn)      { line('> **Hard stop.** ' + p.warn); line(); }
      if (p.warnAmber) { line('> **Caution.** ' + p.warnAmber); line(); }
      line('- [ ] Formulation correct');
      line('- [ ] Sig correct and within the cap');
      line('- [ ] Quantity, unit and days agree');
      line('- [ ] Price and charge code correct');
      line();
    });
  });
}

table(complete, 'Complete — sign off or correct');

table(incomplete, 'Incomplete — fields needed before these can go live',
  'These four have a confirmed name, formulation and days, but no sig or quantity.\n'
  + 'The provider tool renders those fields as "not yet defined" with no copy button,\n'
  + 'so nobody can paste a blank into Tebra, but that also means the product cannot be\n'
  + 'prescribed from the tool until the fields are supplied.');

line('---');
line();
line('## After sign-off');
line();
line('Set `needsSignoff: false` on each approved record in `korb-addons-data.js`, then');
line('run `node build-embed.js` to push the change into the tool and');
line('`node build-embed.js --check` to confirm nothing else drifted.');
line();

process.stdout.write(out.join('\n'));
